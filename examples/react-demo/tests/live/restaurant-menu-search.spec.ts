import { expect, test } from '@playwright/test'

test.use({ viewport: { width: 1280, height: 900 }, video: { mode: 'on', size: { width: 1280, height: 900 } } })

test('JAN-159 live restaurant menu search and reset', async ({ page }) => {
  test.setTimeout(180_000)
  await page.goto('/search')
  await expect(page.locator('html')).toHaveAttribute('data-app-hydrated', 'true')
  await page.getByTestId('search-scope-restaurants').click()
  await page.locator('#catalog-search').fill('sweetgreen')
  await page.getByRole('button', { name: 'Search nearby', exact: true }).click()
  const restaurant = page.getByRole('button', { name: /sweetgreen/i }).first()
  await expect(restaurant).toBeVisible({ timeout: 45_000 })
  await page.waitForTimeout(1800)
  await restaurant.click()
  const results = page.getByTestId('menu-results')
  await expect(results).toBeVisible({ timeout: 60_000 })
  const allCount = await results.getByTestId(/^restaurant-menu-item-/).count()
  expect(allCount).toBeGreaterThan(0)
  await page.locator('#restaurant-menu-search').scrollIntoViewIfNeeded()
  await page.waitForTimeout(2000)
  await page.getByRole('searchbox', { name: 'Search this menu' }).fill('CHICKEN')
  await page.getByRole('button', { name: 'Search menu', exact: true }).click()
  await expect(results).toBeVisible({ timeout: 60_000 })
  const rows = results.getByTestId(/^restaurant-menu-item-/)
  await expect(rows.first()).toBeVisible({ timeout: 60_000 })
  const labels = await rows.allTextContents()
  expect(labels.length).toBeGreaterThan(0)
  expect(labels.every(label => /chicken/i.test(label))).toBe(true)
  await page.waitForTimeout(2500)
  await page.getByRole('searchbox', { name: 'Search this menu' }).fill('jan159-no-such-dish')
  await page.getByRole('button', { name: 'Search menu', exact: true }).click()
  await expect(page.getByTestId('menu-empty')).toContainText('No dishes match', { timeout: 60_000 })
  await page.waitForTimeout(2200)
  await page.getByRole('button', { name: 'Show full menu', exact: true }).click()
  await expect(results.getByTestId(/^restaurant-menu-item-/)).toHaveCount(allCount, { timeout: 60_000 })
  await page.waitForTimeout(2200)
  console.log(JSON.stringify({ api: 'https://partners.january.ai', restaurantQuery: 'sweetgreen', dishQuery: 'CHICKEN', allCount, filteredCount: labels.length, noMatch: true, reset: true }))
})
